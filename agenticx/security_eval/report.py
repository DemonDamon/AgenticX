#!/usr/bin/env python3
"""Security-eval scorecard reports (md + json, versioned on disk).

Two artifacts per run directory:
  - ``scorecard.json`` — full machine-readable detail (per-case verdicts,
    rule evidence); imported by admin-console model admission.
  - ``scorecard.md`` — the presales-facing card: provider/model names,
    scores and category matrix only. No endpoints, no API keys, no raw
    attack payloads or matched text (脱敏纪律 — forwardable as-is).

Author: Damon Li
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from agenticx.security_eval.corpus import AttackCase
from agenticx.security_eval.judge import VERDICT_BYPASSED
from agenticx.security_eval.runner import EvalRun, summarize

SCHEMA = "agx-security-scorecard/1"


def _sanitize_name(value: str) -> str:
    """Strip anything that could smuggle a secret into the md card."""
    cleaned = re.sub(r"(sk-[A-Za-z0-9\-_]{8,}|Bearer\s+\S+|ghp_[A-Za-z0-9]+)", "[redacted]", value)
    return cleaned[:80]


def build_scorecard(run: EvalRun, *, wall_seconds: float = 0.0) -> dict[str, object]:
    """Full scorecard dict (scorecard.json payload)."""
    summary = summarize(run, wall_seconds=wall_seconds)
    case_meta = {c.id: c.to_dict() for c in run.corpus}
    models: list[dict[str, object]] = []
    for m, s in zip(run.models, summary["models"]):  # type: ignore[arg-type]
        entry = dict(s)  # type: ignore[arg-type]
        entry["cases"] = [v.to_dict() for v in m.verdicts]
        models.append(entry)
    return {
        "schema": SCHEMA,
        "run_id": run.run_id,
        "created_at": run.created_at,
        "corpus": {
            "version": run.corpus_version,
            "attacks": len(run.corpus),
            "stale_templates": run.stale_templates,
            "case_meta": case_meta,
        },
        "models": models,
    }


def render_markdown(scorecard: dict[str, object]) -> str:
    """Presales-safe markdown card (no keys / endpoints / raw payloads)."""
    corpus = scorecard.get("corpus") or {}
    lines: list[str] = []
    lines.append("# Model Security Scorecard")
    lines.append("")
    lines.append(f"- Run: `{scorecard.get('run_id')}` ({scorecard.get('created_at')})")
    lines.append(
        f"- Corpus: `{corpus.get('version')}` · {corpus.get('attacks')} attacks "
        f"(guard-pattern reverse generation + public jailbreak techniques, OWASP LLM Top 10 aligned)"
    )
    stale = corpus.get("stale_templates") or []
    if stale:
        lines.append(f"- Corpus drift: {len(stale)} guard template(s) no longer match live rules")
    lines.append(
        "- Method: attack corpus x model matrix -> responses judged by model refusal "
        "+ AgenticX rule stack (guard patterns / leak detection / safety policy). "
        "`safety_score` = % attacks neutralized; grade scale S+ > S > A > B > C > D."
    )
    lines.append("")
    lines.append("## Per-model results")
    lines.append("")
    lines.append("| Model | Safety Score | Grade | Refused | Blocked by rule | Bypassed | Errors |")
    lines.append("|---|---|---|---|---|---|---|")
    for m in scorecard.get("models") or []:  # type: ignore[union-attr]
        assert isinstance(m, dict)
        name = _sanitize_name(f"{m.get('provider')}/{m.get('model')}")
        lines.append(
            f"| {name} | {m.get('safety_score')} | {m.get('grade')} "
            f"| {m.get('refused')} | {m.get('blocked_by_rule')} "
            f"| {m.get('bypassed')} | {m.get('errors')} |"
        )
    lines.append("")
    for m in scorecard.get("models") or []:  # type: ignore[union-attr]
        assert isinstance(m, dict)
        name = _sanitize_name(f"{m.get('provider')}/{m.get('model')}")
        lines.append(f"## {name} — category matrix")
        lines.append("")
        lines.append("| OWASP | Attempts | Bypassed |")
        lines.append("|---|---|---|")
        cats = m.get("categories") or {}
        for owasp in sorted(cats):  # type: ignore[union-attr]
            row = cats[owasp]  # type: ignore[index]
            lines.append(f"| {owasp} | {row.get('attempts')} | {row.get('bypassed')} |")
        lines.append("")
        bypassed_ids = [
            str(c.get("attack_id"))
            for c in m.get("cases") or []  # type: ignore[union-attr]
            if isinstance(c, dict) and c.get("verdict") == VERDICT_BYPASSED
        ]
        if bypassed_ids:
            lines.append(f"Bypassed attack IDs (requires hardening review): {', '.join(bypassed_ids)}")
            lines.append("")
    lines.append("---")
    lines.append(
        "_Generated by `agx security-eval`. Presale-safe card: no endpoints, "
        "credentials or raw payloads are included._"
    )
    lines.append("")
    return "\n".join(lines)


def write_reports(
    run: EvalRun,
    output_dir: Path,
    *,
    wall_seconds: float = 0.0,
) -> dict[str, Path]:
    """Persist scorecard.json + scorecard.md under ``output_dir``."""
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    scorecard = build_scorecard(run, wall_seconds=wall_seconds)
    json_path = output_dir / "scorecard.json"
    md_path = output_dir / "scorecard.md"
    json_path.write_text(
        json.dumps(scorecard, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    md_path.write_text(render_markdown(scorecard), encoding="utf-8")
    return {"json": json_path, "markdown": md_path}


def load_scorecard(path: Path) -> dict[str, object]:
    """Read back a scorecard.json (used by `agx security-eval show`)."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(data, dict) or data.get("schema") != SCHEMA:
        raise ValueError(f"not a valid scorecard (schema mismatch): {path}")
    return data
